#!/usr/bin/env python3
"""Generates the English strings of every setting, and the lookup map that reads them.

WHY: the settings screen shows each setting's title, help, option labels and section
heading in the phone's language. The English lives on the SettingDef declarations
in Kotlin, so each translatable string is copied into app/src/main/res/values/strings.xml
and keyed by the setting key, and SettingTextMap.kt maps the keys to those resources.
Writing that by hand drifted: settings were added and the map fell behind. This script
reads every declaration again and writes both files from the code, so the English in
strings.xml is always the English the code declares.

What it does:
  1. Reads every .kt file under core, android and app source sets (src/main, src/full,
     src/play) and finds each SettingDef constructor call (Toggle, IntValue, FloatValue,
     Choice, Text, Secret) that has a SettingSection argument.
  2. Resolves the key, title, help and option labels. Constants (`const val`), `+`
     concatenation, `SettingsMode.SIMPLE.id`-style enum ids and enum-built option lists
     (`Enum.entries.map { SettingDef.Choice.Option(it.id, it.label) }`) are resolved.
     Anything it cannot evaluate, such as a `$` template, a raw string or a function
     call, is a hard error. It never skips a setting silently.
  3. Rewrites ONLY the block between the BEGIN and END markers in strings.xml, and
     writes SettingTextMap.kt in full. Output is deterministic, so a second run changes
     nothing. `--check` exits 1 when the files are out of date, without writing.

Run it after adding or changing a SettingDef, an option or a section:
    python3 scripts/gen-setting-text.py          (write)
    python3 scripts/gen-setting-text.py --check  (verify, no write)
See docs/build.md, "Setting text".

Stdlib only. Python 3.8 or newer.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULES = ["core", "android", "app"]
SOURCE_SETS = ["src/main/kotlin", "src/full/kotlin", "src/play/kotlin"]
STRINGS = ROOT / "app" / "src" / "main" / "res" / "values" / "strings.xml"
MAP = ROOT / "app" / "src" / "main" / "kotlin" / "dev" / "localintelligence" / "app" / "settings" / "SettingTextMap.kt"
BEGIN = "    <!-- BEGIN setting-text: generated by scripts/gen-setting-text.py, do not edit by hand -->"
END = "    <!-- END setting-text -->"

CTORS = {
    "Toggle": ["key", "title", "help", "section", "default"],
    "IntValue": ["key", "title", "help", "section", "default"],
    "FloatValue": ["key", "title", "help", "section", "default"],
    "Choice": ["key", "title", "help", "section", "default", "options"],
    "Text": ["key", "title", "help", "section", "default"],
    "Secret": ["key", "title", "help", "section"],
}

# Escapes Kotlin allows in a plain string literal that this script understands.
ESCAPES = {"n": "\n", "t": "\t", '"': '"', "'": "'", "\\": "\\", "$": "$"}


class GenError(Exception):
    pass


def fail(where, message):
    raise GenError(f"{where}: {message}")


# ---------------------------------------------------------------- tokenizer

def tokenize(src, where):
    """Kotlin tokens as (kind, value, line). Kinds: STR, ID, NUM, P (one punctuation char)."""
    toks = []
    i, n, line = 0, len(src), 1
    while i < n:
        c = src[i]
        if c == "\n":
            line += 1
            i += 1
        elif c.isspace():
            i += 1
        elif src.startswith("//", i):
            j = src.find("\n", i)
            i = n if j < 0 else j
        elif src.startswith("/*", i):
            j = src.find("*/", i + 2)
            if j < 0:
                fail(where, f"line {line}: unterminated comment")
            line += src.count("\n", i, j)
            i = j + 2
        elif src.startswith('"""', i):
            # A raw string is literal text (no escapes). Anything after it, such as .trimIndent(),
            # is a separate token, so a setting that uses one fails in evaluate() rather than silently.
            j = src.find('"""', i + 3)
            if j < 0:
                fail(where, f"line {line}: unterminated raw string")
            end = j
            while end < n and src[end] == '"':   # a run of quotes closes with its last three
                end += 1
            body = src[i + 3:end - 3]
            line += body.count("\n")
            toks.append(("TPL" if "$" in body else "STR", body, line))
            i = end
        elif c == '"':
            j, buf, template = i + 1, [], False
            while True:
                if j >= n or src[j] == "\n":
                    fail(where, f"line {line}: unterminated string")
                ch = src[j]
                if ch == '"':
                    break
                if ch == "\\":
                    esc = src[j + 1] if j + 1 < n else ""
                    if esc == "u":
                        buf.append(chr(int(src[j + 2:j + 6], 16)))
                        j += 6
                        continue
                    if esc not in ESCAPES:
                        fail(where, f"line {line}: unsupported escape \\{esc}")
                    buf.append(ESCAPES[esc])
                    j += 2
                    continue
                if ch == "$":
                    template = True
                buf.append(ch)
                j += 1
            # A $ template is kept as TPL: fine in model-visible text, an error only if a setting reads it.
            toks.append(("TPL" if template else "STR", "".join(buf), line))
            i = j + 1
        elif c == "'":
            # A char literal such as ',' is kept as CHR; it is an error only where a setting reads it.
            j = i + 2 if i + 1 < n and src[i + 1] != "\\" else i + 3
            if j >= n or src[j] != "'":
                fail(where, f"line {line}: unreadable char literal")
            toks.append(("CHR", src[i:j + 1], line))
            i = j + 1
        elif c.isalpha() or c == "_":
            j = i
            while j < n and (src[j].isalnum() or src[j] == "_"):
                j += 1
            toks.append(("ID", src[i:j], line))
            i = j
        elif c.isdigit():
            j = i
            while j < n and (src[j].isalnum() or src[j] == "_"):
                j += 1
            toks.append(("NUM", src[i:j], line))
            i = j
        else:
            toks.append(("P", c, line))
            i += 1
    return toks


def matching(toks, open_index):
    """Index of the bracket that closes toks[open_index]."""
    pairs = {"(": ")", "[": "]", "{": "}"}
    stack = []
    for k in range(open_index, len(toks)):
        kind, val, _ = toks[k]
        if kind != "P":
            continue
        if val in pairs:
            stack.append(pairs[val])
        elif stack and val == stack[-1]:
            stack.pop()
            if not stack:
                return k
    raise GenError("unbalanced brackets")


def split_top(toks, sep=","):
    """Split a token run on separators at bracket depth 0."""
    parts, cur, depth = [], [], 0
    for t in toks:
        if t[0] == "P" and t[1] in "([{":
            depth += 1
        elif t[0] == "P" and t[1] in ")]}":
            depth -= 1
        if depth == 0 and t[0] == "P" and t[1] == sep:
            parts.append(cur)
            cur = []
        else:
            cur.append(t)
    if cur:
        parts.append(cur)
    return parts


def call_args(toks, open_index):
    """Argument token lists of the call whose '(' is at open_index."""
    close = matching(toks, open_index)
    inner = toks[open_index + 1:close]
    return [a for a in split_top(inner) if a]


def named(arg):
    """(name, value tokens) for `name = value`, or (None, arg) for a positional argument."""
    if len(arg) >= 2 and arg[0][0] == "ID" and arg[1] == ("P", "=", arg[1][2]):
        return arg[0][1], arg[2:]
    return None, arg


# ---------------------------------------------------------------- symbol tables

class Tables:
    def __init__(self):
        self.consts = {}   # NAME -> list of (value, where)
        self.enums = {}    # NAME -> [{"params": [...], "entries": [(entry, {param: tokens})], "where": where}, ...]

    def enum(self, name, where):
        found = self.enums.get(name, [])
        if len(found) != 1:
            fail(where, f"enum {name} is declared {len(found)} times; the reader needs exactly one")
        return found[0]


def index_file(tables, where, toks):
    for k, (kind, val, _) in enumerate(toks):
        if kind == "ID" and val == "val" and k >= 1 and k + 3 < len(toks):
            # `val NAME = "literal"` or `const val NAME = "literal"` (not a property with a getter).
            name_tok = toks[k + 1]
            # `val NAME = "x"` or `val NAME: String = "x"`.
            eq_at = k + 2
            if toks[eq_at] == ("P", ":", toks[eq_at][2]) and eq_at + 2 < len(toks):
                eq_at += 2
            if eq_at + 1 >= len(toks):
                continue
            eq, value_tok = toks[eq_at], toks[eq_at + 1]
            if name_tok[0] == "ID" and eq == ("P", "=", eq[2]) and value_tok[0] == "STR":
                nxt = toks[eq_at + 2] if eq_at + 2 < len(toks) else ("P", "", 0)
                if nxt[0] == "P" and nxt[1] == "+":
                    continue
                tables.consts.setdefault(name_tok[1], []).append((value_tok[1], where))
        if kind == "ID" and val == "enum" and k + 2 < len(toks) and toks[k + 1] == ("ID", "class", toks[k + 1][2]):
            name = toks[k + 2][1]
            j = k + 3
            params = []
            if j < len(toks) and toks[j] == ("P", "(", toks[j][2]):
                close = matching(toks, j)
                for m in range(j, close):
                    if toks[m] == ("ID", "val", toks[m][2]) and toks[m + 1][0] == "ID":
                        params.append(toks[m + 1][1])
                j = close + 1
            if j >= len(toks) or toks[j] != ("P", "{", toks[j][2]):
                continue
            body_close = matching(toks, j)
            body = toks[j + 1:body_close]
            # Entries end at the first top-level ';'; anything after it is members, not entries.
            depth, cut = 0, len(body)
            for m, t in enumerate(body):
                if t[0] == "P" and t[1] in "([{":
                    depth += 1
                elif t[0] == "P" and t[1] in ")]}":
                    depth -= 1
                elif depth == 0 and t == ("P", ";", t[2]):
                    cut = m
                    break
            entries = []
            for piece in split_top(body[:cut]):
                if not piece or piece[0][0] != "ID":
                    continue
                entry = piece[0][1]
                args = {}
                if len(piece) > 1 and piece[1] == ("P", "(", piece[1][2]):
                    for idx, arg in enumerate(call_args(piece, 1)):
                        _, value = named(arg)
                        if idx < len(params):
                            args[params[idx]] = value
                entries.append((entry, args))
            # Two enums can share a name in different packages. Keep both; a setting that uses the
            # name must then fail in lookup() rather than guess which one it means.
            tables.enums.setdefault(name, []).append({"params": params, "entries": entries, "where": where})


def evaluate(tables, toks, where, env=None):
    """A string expression: literals, const refs and factory parameters joined with '+', or fail.

    [env] maps a factory's parameter names to their values at this call site. A $name in a
    template literal is replaced from it; any other $ template is an error.
    """
    if not toks:
        fail(where, "empty expression")
    value = []
    for part in split_top(toks, "+"):
        if len(part) == 1 and part[0][0] in ("STR", "TPL"):
            text = part[0][1]
            if part[0][0] == "TPL":
                if env is None or "${" in text:
                    fail(where, "a $ template in a setting's text; the English must be a fixed text")
                text = re.sub(r"\$([A-Za-z_][A-Za-z0-9_]*)", lambda m: env[m.group(1)] if m.group(1) in env else fail(where, f"${m.group(1)} is not a parameter"), text)
            value.append(text)
            continue
        if len(part) == 1 and part[0][0] == "ID" and env is not None and part[0][1] in env:
            value.append(env[part[0][1]])
            continue
        ids = [t for t in part]
        if not ids or any(t[0] != "ID" and t != ("P", ".", t[2]) for t in ids):
            fail(where, f"cannot evaluate {' '.join(t[1] for t in part)!r}; use a string literal or a const")
        names = [t[1] for t in part if t[0] == "ID"]
        if len(names) == 1 and len(part) == 1:
            found = tables.consts.get(names[0])
            if not found:
                fail(where, f"no string const named {names[0]}")
            if len({v for v, _ in found}) != 1:
                fail(where, f"const {names[0]} has different values in different files")
            value.append(found[0][0])
        elif len(names) == 3 and names[2] in ("id", "label"):
            entry = None
            if names[0] in tables.enums:
                enum = tables.enum(names[0], where)
                entry = next((a for n, a in enum["entries"] if n == names[1]), None)
            if entry is None or names[2] not in entry:
                fail(where, f"cannot resolve {'.'.join(names)}")
            value.append(evaluate(tables, entry[names[2]], where))
        else:
            fail(where, f"cannot evaluate {'.'.join(names)}")
    return "".join(value)


def section_name(toks, where):
    names = [t[1] for t in toks if t[0] == "ID"]
    if len(names) != 2 or names[0] != "SettingSection":
        fail(where, f"section must be SettingSection.X, got {names}")
    return names[1]


# ---------------------------------------------------------------- settings

def find_settings(tables, files):
    """Every setting declared in the files, in file order.

    Two shapes are read: a direct `SettingDef.X(...)` call, and a one-line factory such as
    `private fun secret(key, title, site) = SettingDef.Secret(...)` whose call sites pass literal
    arguments. A factory's own body is read only through its call sites.
    """
    settings = []
    for where, toks in files:
        factories, body_ranges = {}, []
        for k, (kind, val, line) in enumerate(toks):
            if (kind, val) != ("ID", "fun") or k + 2 >= len(toks) or toks[k + 1][0] != "ID":
                continue
            if toks[k + 2] != ("P", "(", line):
                continue
            close = matching(toks, k + 2)
            if close + 3 >= len(toks) or toks[close + 1] != ("P", "=", line):
                continue
            if toks[close + 2] != ("ID", "SettingDef", line) or toks[close + 3] != ("P", ".", line):
                continue
            ctor_open = close + 5
            if ctor_open >= len(toks) or toks[ctor_open] != ("P", "(", line) or toks[close + 4][1] not in CTORS:
                continue
            params = [piece[0][1] for piece in split_top(toks[k + 3:close]) if piece and piece[0][0] == "ID"]
            factories[toks[k + 1][1]] = {"params": params, "ctor": toks[close + 4][1], "args": call_args(toks, ctor_open)}
            body_ranges.append((k, matching(toks, ctor_open)))
        def in_body(i):
            return any(a <= i <= b for a, b in body_ranges)
        for k, (kind, val, line) in enumerate(toks):
            if kind != "ID" or in_body(k) or k + 1 >= len(toks) or toks[k + 1] != ("P", "(", line):
                continue
            site = f"{where}:{line}"
            if k >= 1 and toks[k - 1] == ("ID", "class", line):
                continue
            if val in CTORS:
                args = call_args(toks, k + 1)
                if any(t == ("ID", "SettingSection", t[2]) for a in args for t in a):
                    made = make_setting(tables, val, args, None, site)
                    if made is not None:
                        settings.append(made)
            elif val in factories and k >= 1 and toks[k - 1] == ("P", "=", line):
                factory = factories[val]
                bound = call_args(toks, k + 1)
                env_args = {}
                for name, arg in zip(factory["params"], bound):
                    env_args[name] = evaluate(tables, arg, site)
                if len(bound) != len(factory["params"]):
                    fail(site, f"factory {val} takes {len(factory['params'])} arguments, got {len(bound)}")
                made = make_setting(tables, factory["ctor"], factory["args"], env_args, site)
                if made is not None:
                    settings.append(made)
    return settings


def make_setting(tables, ctor, args, env, site):
    slots = {}
    positional = iter(CTORS[ctor])
    for arg in args:
        name, value = named(arg)
        if name is None:
            name = next(positional, None)
            if name is None:
                fail(site, f"too many positional arguments for {ctor}")
        if name in slots:
            fail(site, f"argument {name} given twice")
        slots[name] = value
    for needed in ("key", "title", "help", "section"):
        if needed not in slots:
            fail(site, f"{ctor} has no {needed}")
    if any(t[0] == "TPL" for t in slots["key"]):
        # A key built at run time (a per-request record) is not on the settings screen and has no
        # fixed English, so there is nothing to translate. Listed on stdout, never silently dropped.
        print(f"gen-setting-text: {site}: dynamic key, not translated (not listed on the screen)")
        return None
    key = evaluate(tables, slots["key"], site, env)
    if not re.fullmatch(r"[a-z0-9_.]+", key):
        fail(site, f"key {key!r} has characters outside [a-z0-9_.]")
    setting = {
        "key": key,
        "title": evaluate(tables, slots["title"], site, env),
        "help": evaluate(tables, slots["help"], site, env),
        "section": section_name(slots["section"], site),
        "where": site,
        "options": [],
    }
    if ctor == "Choice":
        setting["options"] = options_of(tables, slots.get("options"), site, env)
    return setting


def options_of(tables, toks, site, env=None):
    if toks is None:
        fail(site, "Choice without options")
    # Enum-built: `Enum.entries.map { SettingDef.Choice.Option(it.id, it.label) }`.
    names = [t[1] for t in toks if t[0] == "ID"]
    for i in range(len(names) - 1):
        if names[i] in tables.enums and names[i + 1] == "entries":
            enum = tables.enum(names[i], site)
            if "id" not in enum["params"] or "label" not in enum["params"]:
                fail(site, f"enum {names[i]} has no id and label parameters")
            out = []
            for entry, args in enum["entries"]:
                out.append((evaluate(tables, args["id"], enum["where"]), evaluate(tables, args["label"], enum["where"])))
            return out
    out = []
    for k, t in enumerate(toks):
        if t == ("ID", "Option", t[2]) and k + 1 < len(toks) and toks[k + 1] == ("P", "(", t[2]):
            args = call_args(toks, k + 1)
            if len(args) != 2:
                fail(site, "Choice.Option needs an id and a label")
            out.append((evaluate(tables, args[0], site, env), evaluate(tables, args[1], site, env)))
    if not out:
        fail(site, "could not read any option from the options argument")
    return out


def enum_strings(tables, name, param):
    enum = tables.enum(name, "tables")
    return [(entry, evaluate(tables, args[param], enum["where"])) for entry, args in enum["entries"]]


# ---------------------------------------------------------------- output

def xml_text(s, where):
    """The English as aapt will read it: escaped, and with no whitespace it would change."""
    if s != s.strip() or "  " in s:
        fail(where, f"{s!r} has leading, trailing or doubled spaces, which aapt would change")
    if "\\" in s:
        fail(where, f"{s!r} has a backslash")
    out = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    out = out.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if out[:1] in ("@", "?"):
        out = "\\" + out
    return out


def build(root):
    tables = Tables()
    files = []
    for module in MODULES:
        for source in SOURCE_SETS:
            base = root / module / source
            if not base.exists():
                continue
            for path in sorted(base.rglob("*.kt")):
                if "/build/" in str(path):
                    continue
                text = path.read_text(encoding="utf-8")
                where = str(path.relative_to(root))
                # A file that never names SettingSection cannot hold a declaration. Skip it when it
                # uses syntax this reader does not know (a raw string, say), so only real settings
                # files can stop the run.
                if "SettingSection" not in text and "const val" not in text and "val " not in text:
                    continue
                try:
                    toks = tokenize(text, where)
                except GenError:
                    if "SettingSection" in text:
                        raise
                    continue
                index_file(tables, where, toks)
                files.append((where, toks))
    settings = find_settings(tables, files)

    seen_keys = {}
    for s in settings:
        if s["key"] in seen_keys:
            fail(s["where"], f"key {s['key']} is declared twice (first at {seen_keys[s['key']]})")
        seen_keys[s["key"]] = s["where"]

    entries = []   # (resource name, english, where)
    titles, helps, options, sections = [], [], [], []
    for s in settings:
        base = s["key"].replace(".", "_")
        label, desc = f"setting_{base}_label", f"setting_{base}_desc"
        entries += [(label, s["title"], s["where"]), (desc, s["help"], s["where"])]
        titles.append((s["key"], label))
        helps.append((s["key"], desc))
        seen_ids = set()
        for oid, olabel in s["options"]:
            if not re.fullmatch(r"[a-z0-9_]+", oid):
                fail(s["where"], f"option id {oid!r} has characters outside [a-z0-9_]")
            if oid in seen_ids:
                fail(s["where"], f"option id {oid} is listed twice")
            seen_ids.add(oid)
            name = f"setting_{base}_option_{oid}"
            entries.append((name, olabel, s["where"]))
            options.append((f"{s['key']}/{oid}", name))
    section_names = [name for name, _ in tables.enum("SettingSection", "tables")["entries"]]
    for entry, title in enum_strings(tables, "SettingSection", "title"):
        name = f"setting_section_{entry.lower()}"
        entries.append((name, title, "SettingSection"))
        sections.append((entry, name))
    for s in settings:
        if s["section"] not in section_names:
            fail(s["where"], f"section {s['section']} is not a SettingSection entry")

    names = {}
    for name, english, where in entries:
        if name in names:
            fail(where, f"resource name {name} is used twice (also at {names[name][1]})")
        names[name] = (english, where)
    return settings, entries, titles, helps, options, sections


def render_strings(entries, text):
    """strings.xml with the generated block replaced, and old generated entries removed."""
    lines = text.split("\n")
    out, inside = [], False
    for line in lines:
        if line == BEGIN:
            inside = True
            continue
        if inside:
            if line == END:
                inside = False
            continue
        out.append(line)
    # The first run: move the hand-written setting_*_label / _desc entries into the block.
    legacy = re.compile(r'^\s*<string name="setting_[a-z0-9_]+_(label|desc)">.*</string>\s*$')
    kept = []
    generated = {name for name, _, _ in entries}
    for line in out:
        found = re.match(r'^\s*<string name="(setting_[a-z0-9_]+)"', line)
        if found and found.group(1) in generated:
            # Hand-written before this script existed; the block below now owns the name.
            if not line.rstrip().endswith("</string>"):
                raise GenError(f"multi-line entry for {found.group(1)}; move it by hand")
            continue
        if legacy.match(line):
            if not line.rstrip().endswith("</string>"):
                raise GenError(f"multi-line legacy entry: {line}")
            name = re.search(r'name="([^"]+)"', line).group(1)
            print(f"gen-setting-text: dropped {name}: no setting declares it any more")
            continue
        kept.append(line)
    block = [BEGIN]
    for name, english, where in entries:
        attrs = ' formatted="false"' if "%" in english else ""
        block.append(f'    <string name="{name}"{attrs}>{xml_text(english, where)}</string>')
    block.append(END)
    end_index = max(i for i, line in enumerate(kept) if line.strip() == "</resources>")
    result = kept[:end_index] + block + kept[end_index:]
    return "\n".join(result)


def kt_quote(s):
    if not re.fullmatch(r"[A-Za-z0-9_./-]*", s):
        raise GenError(f"{s!r} needs escaping in Kotlin")
    return f'"{s}"'


def render_map(titles, helps, options, sections):
    def block(name, pairs):
        if not pairs:
            return f"    val {name}: Map<String, Int> = emptyMap()\n"
        body = "".join(f"        {kt_quote(k)} to R.string.{v},\n" for k, v in pairs)
        return f"    val {name}: Map<String, Int> = mapOf(\n{body}    )\n"
    return (
        "// GENERATED by scripts/gen-setting-text.py from the SettingDef declarations. Do not edit by hand;\n"
        "// run `python3 scripts/gen-setting-text.py` after changing a setting (see docs/build.md, \"Setting text\").\n"
        "// A missing resource fails the compile, which is the check.\n"
        "package dev.localintelligence.app.settings\n\n"
        "import dev.localintelligence.app.R\n\n"
        "internal object SettingTextMap {\n"
        "    /** Setting key to the label string resource. */\n"
        + block("titles", titles)
        + "    /** Setting key to the help string resource. */\n"
        + block("helps", helps)
        + "    /** \"key/option id\" to the option label string resource. */\n"
        + block("options", options)
        + "    /** SettingSection constant name to the heading string resource. */\n"
        + block("sections", sections)
        + "}\n"
    )


def main(argv):
    check = "--check" in argv
    try:
        settings, entries, titles, helps, options, sections = build(ROOT)
        strings_now = STRINGS.read_text(encoding="utf-8")
        strings_new = render_strings(entries, strings_now)
        map_new = render_map(titles, helps, options, sections)
    except GenError as err:
        print(f"gen-setting-text: {err}", file=sys.stderr)
        return 2
    map_now = MAP.read_text(encoding="utf-8") if MAP.exists() else ""
    stale = [p for p, new, now in ((STRINGS, strings_new, strings_now), (MAP, map_new, map_now)) if new != now]
    print(f"gen-setting-text: {len(settings)} settings, {len(entries)} strings, {len(options)} option labels")
    if check:
        if stale:
            print("gen-setting-text: out of date: " + ", ".join(str(p.relative_to(ROOT)) for p in stale), file=sys.stderr)
            return 1
        return 0
    if strings_new != strings_now:
        STRINGS.write_text(strings_new, encoding="utf-8")
    if map_new != map_now:
        MAP.write_text(map_new, encoding="utf-8")
    print("gen-setting-text: wrote " + (", ".join(str(p.relative_to(ROOT)) for p in stale) or "nothing (already current)"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
