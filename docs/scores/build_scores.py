#!/usr/bin/env python3
"""Builds docs/scores/index.md, and optionally the bundled app file, from result files only.

Reads docs/scores/results/*.json (written by scripts/run-evals.py). Nothing here is typed in by
hand: a number that is not in a result file does not appear on the page.

  docs/scores/build_scores.py                 writes docs/scores/index.md
  docs/scores/build_scores.py --bundle        also writes app/src/main/assets/scores.json

A row is bundled only from a device-app result that is complete (every task ran for every repeat),
has a device class and names its model's repo and file. For each model and device class the newest
such result wins. Everything else stays on the page only.
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
RESULTS = HERE / "results"
INDEX = HERE / "index.md"
BUNDLE = ROOT / "app" / "src" / "main" / "assets" / "scores.json"
SCHEMA = 1


def load_results() -> list[dict]:
    docs = []
    for path in sorted(RESULTS.glob("*.json")):
        doc = json.loads(path.read_text(encoding="utf-8"))
        if doc.get("schemaVersion") != SCHEMA:
            print(f"skipped {path.name}: schemaVersion {doc.get('schemaVersion')}")
            continue
        doc["_file"] = path.name
        docs.append(doc)
    return docs


def fmt(value, unit="", digits=1):
    if value is None:
        return "not measured"
    if isinstance(value, float):
        value = round(value, digits)
    return f"{value}{unit}"


def pct(value):
    return "not measured" if value is None else f"{round(value * 100, 1)}%"


def host_name(doc) -> str:
    if doc["runner"] == "device-app":
        dev = doc.get("device") or {}
        return f"{dev.get('model') or 'unknown phone'} (Android {dev.get('android') or '?'}, {dev.get('device_class') or 'class unknown'})"
    return (doc.get("host") or {}).get("label") or "desktop"


def model_name(doc) -> str:
    m = doc.get("model") or {}
    return m.get("id") or m.get("file") or "unknown model"


def page(docs: list[dict]) -> str:
    lines = [
        "# Scores",
        "",
        "Generated by `docs/scores/build_scores.py` from the result files in `docs/scores/results/`. "
        "Do not edit this page by hand. A value marked *not measured* is absent from its result file.",
        "",
        "Two runners appear in separate tables. **device-app** is the real app on a phone through "
        "`scripts/devicectl.sh`. **desktop-app-loop** is the app's loop on a desktop llama-server, through a "
        "harness; it is not a phone figure. Only device-app complete runs feed the app's Simple setup.",
        "",
        "Verdicts: **pass** and **fail** are decided by the checks in `evals/tasks.jsonl`. **unverified** "
        "means a check could not be decided from what the run could observe, and it counts as not passed.",
        "",
    ]
    if not docs:
        lines += ["No measured results yet. The tables fill in when a run writes its result file.", ""]
        return "\n".join(lines)

    for runner in ("device-app", "desktop-app-loop"):
        group = [d for d in docs if d["runner"] == runner]
        lines += [f"## {runner}", ""]
        if not group:
            lines += ["No results.", ""]
            continue
        lines += [
            "| Model | Host | Pass rate | Pass / fail / unverified | Runs | Median decode tok/s | Median prefill ms | Median first token ms | Median total ms | Peak RAM | Commit | Date |",
            "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---|---|",
        ]
        for d in sorted(group, key=lambda d: (model_name(d), host_name(d), d["run_started"])):
            s = d["summary"]
            med = s["median"]
            peak = s.get("peak_mem_kb_max")
            peak_txt = "not measured" if peak is None else f"{round(peak / 1024)} MB"
            lines.append(
                f"| {model_name(d)} | {host_name(d)} | {pct(s['pass_rate'])}"
                f" | {s['pass']} / {s['fail']} / {s['unverified']}"
                f" | {s['runs']} of {s['expected_runs']}"
                f" | {fmt(med['decode_tok_s'])} | {fmt(med['prefill_ms'], digits=0)}"
                f" | {fmt(med['first_token_ms'], digits=0)} | {fmt(med['total_ms'], digits=0)}"
                f" | {peak_txt} | {d['app']['commit']}{' (dirty)' if d['app'].get('dirty') else ''}"
                f" | {d['run_started'][:10]} |"
            )
        lines.append("")
        for d in sorted(group, key=lambda d: (model_name(d), host_name(d), d["run_started"])):
            cats = d["summary"]["by_category"]
            lines += [
                f"### {model_name(d)}, {host_name(d)}, {d['run_started'][:10]}",
                "",
                "| Category | Runs | Pass | Fail | Unverified | Pass rate |",
                "|---|---:|---:|---:|---:|---:|",
            ]
            for name in sorted(cats):
                c = cats[name]
                lines.append(f"| {name} | {c['n']} | {c['pass']} | {c['fail']} | {c['unverified']} | {pct(c['pass_rate'])} |")
            lines.append("")
    return "\n".join(lines) + "\n"


def bundle_rows(docs: list[dict]) -> dict:
    newest: dict[tuple, dict] = {}
    for d in docs:
        if d["runner"] != "device-app" or not d["summary"].get("complete"):
            continue
        dev = d.get("device") or {}
        model = d.get("model") or {}
        if not dev.get("device_class") or not model.get("repo") or not model.get("file"):
            continue
        key = (model["repo"], model["file"], dev["device_class"])
        if key not in newest or d["run_started"] > newest[key]["run_started"]:
            newest[key] = d
    rows = []
    for (repo, file, cls), d in sorted(newest.items()):
        s = d["summary"]
        rows.append({
            "repo": repo,
            "file": file,
            "deviceClass": cls,
            "passRate": s["pass_rate"],
            "decodeTokPerS": s["median"]["decode_tok_s"],
            "runs": s["runs"],
        })
    return {"schemaVersion": SCHEMA, "rows": rows}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bundle", action="store_true", help="also write app/src/main/assets/scores.json")
    args = ap.parse_args()
    docs = load_results()
    INDEX.write_text(page(docs), encoding="utf-8")
    print(f"wrote {INDEX} from {len(docs)} result file(s)")
    if args.bundle:
        data = bundle_rows(docs)
        BUNDLE.parent.mkdir(parents=True, exist_ok=True)
        BUNDLE.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {BUNDLE} with {len(data['rows'])} row(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
